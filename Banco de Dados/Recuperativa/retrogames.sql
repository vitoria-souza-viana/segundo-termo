DROP DATABASE IF EXISTS RECUPERATIVA_RETROGAME_VITORIA;

CREATE DATABASE IF NOT EXISTS RECUPERATIVA_RETROGAME_VITORIA;

USE  RECUPERATIVA_RETROGAME_VITORIA;

CREATE TABLE PLATAFORMA (
    ID_PLATAFORMA INT PRIMARY KEY AUTO_INCREMENT,
    NOME VARCHAR(80) NOT NULL UNIQUE
 );

 CREATE TABLE CATEGORIA (
    ID_CATEGORIA INT PRIMARY KEY AUTO_INCREMENT,
    DESCRICAO VARCHAR(80) NOT NULL UNIQUE
 );

 CREATE TABLE CLIENTE  (
    ID_CLIENTE INT PRIMARY KEY AUTO_INCREMENT,
    NOME VARCHAR(100) NOT NULL UNIQUE,
    EMAIL VARCHAR(120) NOT NULL UNIQUE,
    TELEFONE VARCHAR(20),
    ATIVO  BOOLEAN DEFAULT TRUE

);

CREATE TABLE JOGO (
    ID_JOGO INT PRIMARY KEY AUTO_INCREMENT,
    TITULO VARCHAR(150) NOT NULL ,
    CODIGO VARCHAR (15) NOT NULL UNIQUE,
    ANO_LANCAMENTO INT NOT NULL,
    QUANTIDADE_DISPONIVEL INT DEFAULT 0 CHECK( QUANTIDADE_DISPONIVEL >= 0),
    ID_PLATAFORMA INT,
    ID_CATEGORIA INT,
    CONSTRAINT FK_ID_PLATAFORMA  FOREIGN KEY  (ID_PLATAFORMA) REFERENCES PLATAFORMA (ID_PLATAFORMA),
    CONSTRAINT FK_ID_CATEGORIA FOREIGN KEY (ID_CATEGORIA) REFERENCES CATEGORIA (ID_CATEGORIA)

);

CREATE TABLE LOCACAO (
    ID_LOCACAO INT AUTO_INCREMENT PRIMARY KEY,
    DATA_RETIRADA DATETIME DEFAULT  CURRENT_TIMESTAMP,
    DATA_DEVOLUCAO DATE NULL,
    STATUS_LOCACAO VARCHAR(20) DEFAULT 'ABERTA' CHECK (STATUS_LOCACAO IN ('ABERTA', 'DEVOLVIDO', 'ATRASADO')),
    ID_CLIENTE INT,
    ID_JOGO INT,

    CONSTRAINT FK_ID_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE (ID_CLIENTE),
    CONSTRAINT FK_ID_JOGO FOREIGN KEY (ID_JOGO) REFERENCES JOGO (ID_JOGO)
);


